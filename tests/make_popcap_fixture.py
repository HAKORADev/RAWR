#!/usr/bin/env python3
"""Builds a synthetic PopCap installation to test RAWR end to end.

A PopCap trial install has a stub executable in front of the real game,
which PopCap drops in as a hidden popcapgame1.exe. The trial state also
lives in partner.xml as NoReg="true".

The fixture imitates that layout with generated bytes, so the test can run
everywhere without shipping anyone's game.

Usage: make_popcap_fixture.py <output folder>
"""

import os
import sys


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    root = sys.argv[1]
    os.makedirs(root, exist_ok=True)

    # The real game, hidden.
    game = os.path.join(root, "popcapgame1.exe")
    with open(game, "wb") as f:
        f.write(b"MZ" + b"\x00" * 62)
        f.write(b"\x90" * 4096)          # stand in for a program
    os.system('chmod 644 "%s"' % game)

    # The trial stub that fronts it.
    with open(os.path.join(root, "FixturePop.exe"), "wb") as f:
        f.write(b"MZ" + b"\x00" * 62)
        f.write(b"\xCC" * 2048)

    # The uninstaller and the protection tool, which are never the game.
    for name in ("unins000.exe", "CDProtect.exe"):
        with open(os.path.join(root, name), "wb") as f:
            f.write(b"MZ" + b"\x00" * 62)

    # The trial flag.
    with open(os.path.join(root, "partner.xml"), "w") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
        f.write('<GamePartner NoReg="true" GameName="Fixture Pop" />\n')

    print("popcap fixture written to %s" % root)
    return 0


if __name__ == "__main__":
    sys.exit(main())
